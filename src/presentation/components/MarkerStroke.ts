/**
 * MarkerStroke Component for DSH Cult Canvas
 *
 * Implements freehand marker strokes ported from cult-canvas:
 * - Outline and centerline SVG paths using domain geometry algorithms
 * - 5 palette colors (#1E1E1E, #E03E3E, #2F9E44, #1971C2, #F08C00)
 * - Stroke widths 2-24px with clamp protection
 * - Hit testing and selection highlight
 *
 * @module @local/dsh-cult-canvas/presentation/components/MarkerStroke
 */

import {
	centerlinePath,
	strokeOutlinePath,
	strokeOutlinePoints,
} from "../../domain/geometry.js";
import { type ClientNode, h } from "./react-binding.js";

/** 5 standard whiteboard marker palette colors. */
export const MARKER_PALETTE_COLORS = [
	"#1E1E1E", // Ink / Dark Charcoal
	"#E03E3E", // Vibrant Red
	"#2F9E44", // Forest Green
	"#1971C2", // Azure Blue
	"#F08C00", // Warm Orange
] as const;

export type MarkerPaletteColor = (typeof MARKER_PALETTE_COLORS)[number];

/** Preset marker stroke widths in pixels (2px to 24px). */
export const MARKER_PRESET_WIDTHS = [2, 4, 8, 16, 24] as const;

export const DEFAULT_MARKER_COLOR = MARKER_PALETTE_COLORS[0];
export const DEFAULT_MARKER_WIDTH = 4;
export const MIN_MARKER_WIDTH = 2;
export const MAX_MARKER_WIDTH = 24;

/** Clamps marker width into the valid 2-24px range. */
export function clampMarkerStrokeWidth(width: unknown): number {
	const n = Math.round(Number(width));
	if (!Number.isFinite(n)) return DEFAULT_MARKER_WIDTH;
	return Math.min(MAX_MARKER_WIDTH, Math.max(MIN_MARKER_WIDTH, n));
}

/** Generates closed SVG polygon path for the smooth outline of a stroke. */
export function generateMarkerOutlinePath(
	points: Array<[number, number]>,
	size = DEFAULT_MARKER_WIDTH,
): string {
	const clamped = clampMarkerStrokeWidth(size);
	return strokeOutlinePath(points, clamped);
}

/** Generates centerline SVG path for hit testing or lightweight wireframe rendering. */
export function generateMarkerCenterlinePath(
	points: Array<[number, number]>,
): string {
	return centerlinePath(points);
}

export interface MarkerStrokeProps {
	id?: string;
	points: Array<[number, number]>;
	width?: number;
	color?: string;
	opacity?: number;
	isSelected?: boolean;
	className?: string;
	onSelect?: (id?: string) => void;
	onPointerDown?: (id?: string, e?: unknown) => void;
	onClick?: (e: unknown) => void;
}

/**
 * Freehand Marker Stroke SVG Component.
 */
export function MarkerStroke({
	id,
	points,
	width = DEFAULT_MARKER_WIDTH,
	color = DEFAULT_MARKER_COLOR,
	opacity = 1,
	isSelected = false,
	className,
	onSelect,
	onPointerDown,
	onClick,
}: MarkerStrokeProps): ClientNode {
	if (!points || points.length === 0) {
		return null;
	}

	const clampedWidth = clampMarkerStrokeWidth(width);
	const outlineD = generateMarkerOutlinePath(points, clampedWidth);
	const centerlineD = generateMarkerCenterlinePath(points);

	const hitWidth = Math.max(14, clampedWidth + 10);
	const cls = [
		"dsh-cult-canvas-marker-stroke",
		isSelected ? "selected" : "",
		className ?? "",
	]
		.filter(Boolean)
		.join(" ");

	const handleClick = (e: unknown) => {
		if (onClick) onClick(e);
		if (onSelect) onSelect(id);
	};

	const handlePointerDown = (e: unknown) => {
		if (
			e &&
			typeof (e as { stopPropagation?: () => void }).stopPropagation ===
				"function"
		) {
			(e as { stopPropagation: () => void }).stopPropagation();
		}
		if (onPointerDown) onPointerDown(id, e);
	};

	return h(
		"g",
		{
			id: id ? `stroke-${id}` : undefined,
			className: cls,
			onClick: handleClick,
			onPointerDown: handlePointerDown,
			style: { cursor: "pointer" },
		},
		// 1. Invisible wide hit area for easy selection / hovering
		h("path", {
			className: "dsh-marker-hit-area",
			d: centerlineD,
			stroke: "transparent",
			strokeWidth: hitWidth,
			strokeLinecap: "round",
			strokeLinejoin: "round",
			fill: "none",
			pointerEvents: "stroke",
		}),
		// 2. Filled smooth outline path generated by strokeOutlinePoints
		h("path", {
			className: "dsh-marker-fill",
			d: outlineD,
			fill: color,
			fillOpacity: opacity,
			pointerEvents: "none",
		}),
		// 3. Selection halo if selected
		isSelected
			? h("path", {
					className: "dsh-marker-selection-halo",
					d: centerlineD,
					stroke: "var(--dsh-accent, #38bdf8)",
					strokeWidth: clampedWidth + 6,
					strokeLinecap: "round",
					strokeLinejoin: "round",
					strokeDasharray: "4 4",
					fill: "none",
					pointerEvents: "none",
					opacity: 0.85,
				})
			: null,
	);
}

export { strokeOutlinePoints, strokeOutlinePath, centerlinePath };
